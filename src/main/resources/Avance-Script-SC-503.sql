-- Script para la creación de usuario, tablespace y tablas del proyecto de estacionamiento
-- Ejecutar como usuario SYS con privilegios AS SYSDBA
-- Oracle SQL Developer

SET SERVEROUTPUT ON;

-- Desactivar la restricción de prefijo C## (permite crear usuarios sin prefijo)
ALTER SESSION SET "_ORACLE_SCRIPT"=TRUE; 
-- Verificar y eliminar usuario existente
DECLARE
  user_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO user_exists FROM dba_users WHERE username = 'PROY_ADMIN';
  IF user_exists > 0 THEN
    EXECUTE IMMEDIATE 'DROP USER PROY_ADMIN CASCADE';
    DBMS_OUTPUT.PUT_LINE('Usuario PROY_ADMIN eliminado.');
  END IF;
END;
/

-- Verificar y eliminar tablespace existente
DECLARE
  ts_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO ts_exists FROM dba_tablespaces WHERE tablespace_name = 'PROYECTO';
  IF ts_exists > 0 THEN
    EXECUTE IMMEDIATE 'DROP TABLESPACE PROYECTO INCLUDING CONTENTS AND DATAFILES';
    DBMS_OUTPUT.PUT_LINE('Tablespace PROYECTO eliminado.');
  END IF;
END;
/

-- Creación del tablespace
-- Para sistemas Mac/Linux con Docker:
CREATE TABLESPACE PROYECTO
    DATAFILE '/opt/oracle/oradata/ORCLCDB/PROYECTO-ADMIN.DBF' 
    SIZE 500M 
    AUTOEXTEND ON 
    NEXT 10M 
    MAXSIZE 5000M;

-- Para sistemas Windows (comentar la sección anterior y descomentar esta sección):
/*
CREATE TABLESPACE PROYECTO
